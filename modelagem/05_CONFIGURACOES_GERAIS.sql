/*
OBJETIVO
- Criar a configuracao singleton do sistema.
- Manter o perfil padrao de primeiro acesso como referencia para PERFIL.
- Inicializar a configuracao sem perfil selecionado; a definicao sera feita por root.

OBSERVACOES
- O script pode ser executado em base nova ou ja populada.
- A coluna SINGLETON e protegida por CHECK e UNIQUE para permitir apenas um registro.
*/

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO V_COUNT
      FROM ALL_TABLES
     WHERE OWNER = 'TODO_LIST'
       AND TABLE_NAME = 'CONFIGURACOES_GERAIS';

    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE TODO_LIST.CONFIGURACOES_GERAIS (
                ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                SINGLETON NUMBER(1) DEFAULT 1 NOT NULL,
                PERFIL_PADRAO_PRIMEIRO_ACESSO_ID NUMBER,
                CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP(6),
                CONSTRAINT PK_CONFIGURACOES_GERAIS PRIMARY KEY (ID),
                CONSTRAINT UK_CONFIGURACOES_GERAIS_SINGLETON UNIQUE (SINGLETON),
                CONSTRAINT CK_CONFIGURACOES_GERAIS_SINGLETON CHECK (SINGLETON = 1),
                CONSTRAINT FK_CONFIG_GERAIS_PERFIL_PRIMEIRO_ACESSO
                    FOREIGN KEY (PERFIL_PADRAO_PRIMEIRO_ACESSO_ID)
                    REFERENCES TODO_LIST.PERFIL (ID)
            )
        ]';
    END IF;
END;
/

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO V_COUNT
      FROM ALL_INDEXES
     WHERE OWNER = 'TODO_LIST'
       AND INDEX_NAME = 'IDX_CONFIG_GERAIS_PERFIL_PRIMEIRO_ACESSO';

    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX TODO_LIST.IDX_CONFIG_GERAIS_PERFIL_PRIMEIRO_ACESSO
                ON TODO_LIST.CONFIGURACOES_GERAIS (PERFIL_PADRAO_PRIMEIRO_ACESSO_ID)
        ';
    END IF;
END;
/

MERGE INTO TODO_LIST.CONFIGURACOES_GERAIS DESTINO
USING (
    SELECT 1 AS SINGLETON FROM DUAL
) ORIGEM
ON (DESTINO.SINGLETON = ORIGEM.SINGLETON)
WHEN NOT MATCHED THEN
    INSERT (SINGLETON)
    VALUES (ORIGEM.SINGLETON);
